function getCategoryById(id) {
  if (!id) return null
  return CLUB_CATEGORIES.find((category) => category.id === id) || null
}

// 由主色推导主题（渐变 / 浅底 / 深色 / 阴影），与后台单色配置解耦
function themeFromColor(color) {
  const hex = /^#[0-9a-fA-F]{6}$/.test(color || '') ? color : '#2E6BFF'
  const r = parseInt(hex.slice(1, 3), 16)
  const g = parseInt(hex.slice(3, 5), 16)
  const b = parseInt(hex.slice(5, 7), 16)
  const mix = (c, ratio) => Math.round(c + (255 - c) * ratio)
  const toHex = (rr, gg, bb) => '#' + [rr, gg, bb].map((v) => v.toString(16).padStart(2, '0')).join('')
  return {
    gradient: 'linear-gradient(135deg, ' + toHex(mix(r, 0.25), mix(g, 0.25), mix(b, 0.25)) + ' 0%, ' + hex + ' 100%)',
    soft: toHex(mix(r, 0.9), mix(g, 0.9), mix(b, 0.9)),
    deep: hex,
    shadow: 'rgba(' + r + ', ' + g + ', ' + b + ', 0.30)'
  }
}

// 服务端分类行 → 前台渲染结构（与 CLUB_CATEGORIES 字段一致）
function mapServerCategory(row) {
  return {
    id: String(row.slug || row.id),
    name: row.name || '',
    char: row.iconChar || (row.name || '').charAt(0),
    slogan: row.slogan || '',
    theme: themeFromColor(row.color),
    position: row.position || '',
    scopeIntro: row.scopeIntro || '',
    scope: Array.isArray(row.scope) ? row.scope : [],
    features: Array.isArray(row.features) ? row.features : [],
    contact: row.contact || '',
    clubs: (Array.isArray(row.clubs) ? row.clubs : []).map((club) => ({
      name: club.name || '',
      tags: club.tags || '',
      intro: club.intro || '',
      recruit: club.recruit || ''
    }))
  }
}

// 拉取服务端社团分类；接口异常或为空时回退到本地内置数据
function fetchCategories() {
  const api = require('./api')
  return api.getClubCategories().then((res) => {
    const list = (res && res.list) || []
    if (!list.length) return CLUB_CATEGORIES
    return list.map(mapServerCategory)
  }).catch(() => CLUB_CATEGORIES)
}

