function getServiceList() {
  return SERVICES.map((item) => ({
    id: item.id,
    name: item.name,
    icon: item.icon,
    tagline: item.tagline
  }))
}

function getServiceById(id) {
  const target = String(id || '')
  return SERVICES.find((item) => item.id === target) || null
}

// 关键信息是否已由运营填写（未填写时页面走降级展示，不留空白区块）
function hasServiceInfo(service) {
  const info = (service && service.info) || null
  return !!(info && Array.isArray(info.items) && info.items.length)
}

